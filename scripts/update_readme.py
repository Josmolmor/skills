#!/usr/bin/env python3
"""Regenerate the skills table in README.md from each skills/*/SKILL.md.

Usage:
  python3 scripts/update_readme.py          # rewrite README.md in place
  python3 scripts/update_readme.py --check  # exit 1 if README.md is out of date

Standard library only. The table goes between these markers in README.md:
  <!-- skills-table:start -->
  <!-- skills-table:end -->
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
SKILLS_DIR = ROOT / "skills"
START = "<!-- skills-table:start -->"
END = "<!-- skills-table:end -->"
NOTE = "<!-- Generated by scripts/update_readme.py from each SKILL.md. Do not edit by hand. -->"


def fail(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        value = value[1:-1]
    return value


def parse_frontmatter(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"^---\s*\n(.*?)\n---\s*(\n|$)", text, re.DOTALL)
    if not match:
        fail(f"{path.relative_to(ROOT)}: missing YAML frontmatter")
    fields: dict[str, str] = {}
    key = None
    for line in match.group(1).splitlines():
        top = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", line)
        if top:
            key, value = top.group(1), top.group(2)
            # Block scalars (| or >) are folded onto one line below.
            fields[key] = "" if value.strip() in ("|", ">", "|-", ">-") else unquote(value)
        elif key and line.startswith((" ", "\t")):
            fields[key] = (fields[key] + " " + line.strip()).strip()
    return fields


def build_table() -> str:
    rows = []
    for skill_md in sorted(SKILLS_DIR.glob("*/SKILL.md")):
        folder = skill_md.parent.name
        meta = parse_frontmatter(skill_md)
        name = meta.get("name", "")
        description = " ".join(meta.get("description", "").split())
        if not name or not description:
            fail(f"{skill_md.relative_to(ROOT)}: frontmatter needs both 'name' and 'description'")
        if name != folder:
            fail(f"{skill_md.relative_to(ROOT)}: name '{name}' must match folder '{folder}'")
        description = description.replace("|", "\\|")
        rows.append(f"| [`{name}`](skills/{folder}/SKILL.md) | {description} |")
    if not rows:
        return "_No skills yet._"
    return "\n".join(["| Skill | What it does |", "| --- | --- |", *rows])


def main() -> None:
    check = "--check" in sys.argv[1:]
    readme = README.read_text(encoding="utf-8")
    if START not in readme or END not in readme:
        fail(f"README.md must contain {START} and {END}")
    before, rest = readme.split(START, 1)
    _, after = rest.split(END, 1)
    updated = f"{before}{START}\n{NOTE}\n{build_table()}\n{END}{after}"

    if updated == readme:
        print("README.md is up to date.")
        return
    if check:
        fail("README.md skills table is out of date. Run: python3 scripts/update_readme.py")
    README.write_text(updated, encoding="utf-8")
    print("README.md updated.")


if __name__ == "__main__":
    main()
